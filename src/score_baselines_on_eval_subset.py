"""
score_baselines_on_eval_subset.py

Re-scores the three classical baselines on the SAME stratified evaluation
subset used for both LLM pipelines (llm_eval_subset.csv)

Usage:
    python score_baselines_on_eval_subset.py --processed-dir data/processed --models-dir results/models --output-dir results
"""

import argparse
import json
from pathlib import Path

import joblib
import pandas as pd
from sklearn.metrics import (
    accuracy_score, average_precision_score, confusion_matrix,
    f1_score, precision_score, recall_score, roc_auc_score,
)

MODEL_NAMES = ["logistic_regression", "random_forest", "xgboost"]


def evaluate(pipeline, X, y):
    y_pred = pipeline.predict(X)
    y_proba = pipeline.predict_proba(X)[:, 1]
    metrics = {
        "accuracy": accuracy_score(y, y_pred),
        "precision": precision_score(y, y_pred),
        "recall": recall_score(y, y_pred),
        "f1": f1_score(y, y_pred),
        "roc_auc": roc_auc_score(y, y_proba),
        "pr_auc": average_precision_score(y, y_proba),
        "confusion_matrix": confusion_matrix(y, y_pred).tolist(),
    }
    return metrics, y_pred, y_proba


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--processed-dir", type=Path, required=True)
    parser.add_argument("--models-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()

    with open(args.processed_dir / "metadata.json") as f:
        metadata = json.load(f)
    subset_path = args.processed_dir / "llm_eval_subset.csv"
    if not subset_path.exists():
        raise SystemExit(
            f"{subset_path} not found -- run select_stratified_subset.py first."
        )
    subset = pd.read_csv(subset_path)

    versions_path = args.models_dir / "_training_versions.json"
    if versions_path.exists():
        import sklearn
        import xgboost
        with open(versions_path) as f:
            trained = json.load(f)
        current = {"sklearn": sklearn.__version__, "xgboost": xgboost.__version__}
        mismatches = {k: (trained.get(k), current[k]) for k in current if trained.get(k) != current[k]}
        if mismatches:
            print("WARNING: package versions differ from when these models were trained:")
            for pkg, (old, new) in mismatches.items():
                print(f"  {pkg}: trained with {old}, currently running {new}")

    target_col = metadata["target_col"]
    feature_cols = metadata["feature_cols"] + metadata["indicator_cols"]
    missing = [c for c in feature_cols if c not in subset.columns]
    if missing:
        raise SystemExit(
            f"Eval subset is missing expected feature columns: {missing[:5]}"
            f"{'...' if len(missing) > 5 else ''}. Was it generated by the "
            f"current select_stratified_subset.py?"
        )
    X = subset[feature_cols]
    y = subset[target_col]

    print(f"Scoring on {len(subset)} cases from the eval subset (NOT the full test set)")

    all_results = {}
    per_case = subset[["case_id", target_col]].rename(columns={target_col: "true_label"})

    for name in MODEL_NAMES:
        model_path = args.models_dir / f"{name}.joblib"
        if not model_path.exists():
            print(f"WARNING: {model_path} not found, skipping {name}")
            continue
        pipeline = joblib.load(model_path)
        metrics, y_pred, y_proba = evaluate(pipeline, X, y)
        all_results[name] = metrics

        per_case[f"{name}_pred"] = y_pred
        per_case[f"{name}_proba"] = y_proba

        print(f"{name:20s} accuracy={metrics['accuracy']:.3f}  f1={metrics['f1']:.3f}  "
              f"roc_auc={metrics['roc_auc']:.3f}")

    if not all_results:
        raise SystemExit("No baseline models found -- run baselines.py first.")

    args.output_dir.mkdir(parents=True, exist_ok=True)
    with open(args.output_dir / "baseline_results_on_eval_subset.json", "w") as f:
        json.dump(all_results, f, indent=2, default=str)

    summary = pd.DataFrame(all_results).T[
        ["accuracy", "precision", "recall", "f1", "roc_auc", "pr_auc"]
    ]
    summary.to_csv(args.output_dir / "baseline_summary_on_eval_subset.csv")

    per_case.to_csv(args.output_dir / "baseline_per_case_predictions.csv", index=False)

    print(f"\nSaved to {args.output_dir}:")
    print("  baseline_results_on_eval_subset.json  (full metrics incl. confusion matrix)")
    print("  baseline_summary_on_eval_subset.csv    (headline metrics table)")
    print("  baseline_per_case_predictions.csv      (for McNemar's test / joining against LLM results)")


if __name__ == "__main__":
    main()
